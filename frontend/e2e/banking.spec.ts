test('credit updates the persisted account balance', async ({ page }) => {
  await login(page, 'Customer');
  await page.goto('/customer/deposit');
  await expect(page.locator('#accountId option')).not.toHaveCount(1);
  const accountId = await page.locator('#accountId option').nth(1).getAttribute('value');
  expect(accountId).toBeTruthy();
  const token = await page.evaluate(() => sessionStorage.getItem('digital-banking-token') || localStorage.getItem('digital-banking-token'));
  const headers = { Authorization: `Bearer ${token}` };
  const beforeResponse = await page.request.get(`/api/accounts/${accountId}`, { headers });
  expect(beforeResponse.ok()).toBe(true);
  const before = await beforeResponse.json();
  await page.getByLabel('Select Account').selectOption(accountId!);
  await page.getByLabel('Amount', { exact: true }).fill('1.25');
  await page.getByLabel('Description').fill(`E2E credit ${Date.now()}`);
  const mutation = page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes('credit'));
  await page.locator('button[type="submit"]').click();
  expect((await mutation).ok()).toBe(true);
  await expect.poll(async () => {
    const after = await (await page.request.get(`/api/accounts/${accountId}`, { headers })).json();
    return Math.round((after.balance - before.balance) * 100);
  }).toBe(125);
});

test('transfer review, concurrent replay and conflicting retry preserve balances', async ({ page }) => {
  await login(page, 'Customer');
  await page.goto('/customer/transfer');
  await expect(page.locator('#fromAccountId option')).not.toHaveCount(1);
  const token = await page.evaluate(() => sessionStorage.getItem('digital-banking-token') || localStorage.getItem('digital-banking-token'));
  const headers = { Authorization: `Bearer ${token}` };
  const accountsResponse = await page.request.get('/api/customer/accounts', { headers });
  expect(accountsResponse.ok()).toBe(true);
  const accounts = (await accountsResponse.json()).filter((a: any) => a.status === 'ACTIVATED');
  expect(accounts.length).toBeGreaterThanOrEqual(2);
  const [source, destination] = accounts;
  await page.getByLabel('From Account', { exact: true }).selectOption(source.id);
  await page.getByLabel('To Account ID', { exact: true }).fill(destination.id);
  await page.getByLabel('Amount', { exact: true }).fill('0.25');
  await page.getByLabel('Description', { exact: true }).fill('E2E transfer review');
  let submitted = 0;
  page.on('request', request => {
    if (request.method() === 'POST' && request.url().endsWith('/transfer')) submitted++;
  });
  await page.getByRole('button', { name: 'Review transfer', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Confirm transfer', exact: true })).toBeEnabled();
  await expect(page.getByLabel('Amount', { exact: true })).toBeDisabled();
  expect(submitted).toBe(0);
  const responsePromise = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/transfer'));
  await page.getByRole('button', { name: 'Confirm transfer', exact: true }).click();
  const response = await responsePromise;
  expect(response.ok()).toBe(true);
  const receipt = await response.json();
  const key = response.request().headers()['idempotency-key'];
  expect(key).toBeTruthy();
  await expect(page.getByRole('status')).toContainText(receipt.id);
  const data = response.request().postDataJSON();
  const replayHeaders = { ...headers, 'Idempotency-Key': key };
  const retries = await Promise.all(Array.from({ length: 5 }, () => page.request.post('/api/transactions/transfer', { headers: replayHeaders, data })));
  for (const retry of retries) {
    expect(retry.ok()).toBe(true);
    expect(await retry.json()).toEqual(receipt);
  }
  const conflict = await page.request.post('/api/transactions/transfer', { headers: replayHeaders, data: { ...data, amount: 0.5 } });
  expect(conflict.status()).toBe(409);
  const afterSource = await (await page.request.get(`/api/accounts/${source.id}`, { headers })).json();
  const afterDestination = await (await page.request.get(`/api/accounts/${destination.id}`, { headers })).json();
  expect(Math.round((afterSource.balance - source.balance) * 100)).toBe(-25);
  expect(Math.round((afterDestination.balance - destination.balance) * 100)).toBe(25);
  const invalid = await page.request.post('/api/transactions/transfer', {
    headers: { ...headers, 'Idempotency-Key': randomUUID() }, data: { ...data, destinationAccountId: 'missing-e2e-account' },
  });
  expect(invalid.status()).toBe(404);
  const unchanged = await (await page.request.get(`/api/accounts/${source.id}`, { headers })).json();
  expect(unchanged.balance).toBe(afterSource.balance);
});
